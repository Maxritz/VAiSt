/* ── GEMM dispatch (f32) ──────────────────────────────────────────────────── */

static VkResult vkblas_sgemm_common(VkBLASContext*  ctx,
                                    VkCommandBuffer  cmd,
                                    VkBLASOperation_t transA,
                                    VkBLASOperation_t transB,
                                    int32_t          m,
                                    int32_t          n,
                                    int32_t          k,
                                    const float*     alpha,
                                    VkBuffer         A,
                                    int32_t          lda,
                                    VkBuffer         B,
                                    int32_t          ldb,
                                    const float*     beta,
                                    VkBuffer         C,
                                    int32_t          ldc,
                                    VkBuffer         D,
                                    int32_t          ldd,
                                    uint32_t         strideA,
                                    uint32_t         strideB,
                                    uint32_t         strideC,
                                    uint32_t         strideD,
                                    int32_t          batchCount,
                                    VkBool32         is_strided)
{
    /* Ensure pipeline exists */
    uint32_t tA = (transA == VKBLAS_OP_N) ? 0 : 1;
    uint32_t tB = (transB == VKBLAS_OP_N) ? 0 : 1;

    VkPipeline pipeline = VK_NULL_HANDLE;
    VkResult r = vkblas_ensure_pipeline(ctx, VKBLAS_DTYPE_F32, tA, tB, is_strided,
                                        &pipeline);
    if (r != VK_SUCCESS)
        return r;

    /* Allocate descriptor set */
    VkDescriptorSet ds;
    r = vkblas_alloc_descriptor_set(ctx, &ds);
    if (r != VK_SUCCESS)
        return r;

    vkblas_write_descriptor_set(ctx, ds, A, B,
                                (C != VK_NULL_HANDLE) ? C : A, D);
    /* Use A as dummy for C when beta==0 (read-only binding won't be accessed) */

    /* Bind pipeline and descriptor set */
    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE,
                            ctx->pipeline_layout, 0, 1, &ds, 0, NULL);

    /* Push constants */
    vkblas_push_constants_t pc = {0};
    pc.m = (uint32_t)m;
    pc.n = (uint32_t)n;
    pc.k = (uint32_t)k;
    pc.alpha = (alpha != NULL) ? *alpha : 1.0f;
    pc.beta = (beta != NULL) ? *beta : 0.0f;
    pc.lda = (uint32_t)lda;
    pc.ldb = (uint32_t)ldb;
    pc.ldc = (uint32_t)ldc;
    pc.ldd = (uint32_t)ldd;
    pc.transA = (int32_t)tA;
    pc.transB = (int32_t)tB;
    pc.beta_is_zero = (pc.beta == 0.0f) ? 1 : 0;
    pc.strideA = strideA;
    pc.strideB = strideB;
    pc.strideC = strideC;
    pc.strideD = strideD;
    pc.batchCount = (uint32_t)batchCount;
    vkblas_push_pc(cmd, ctx->pipeline_layout, &pc);

    /* Compute grid: one workgroup per TILE_M × TILE_N output block */
    uint32_t gridX = (uint32_t)((m + VKBLAS_TILE_M - 1) / VKBLAS_TILE_M);
    uint32_t gridY = (uint32_t)((n + VKBLAS_TILE_N - 1) / VKBLAS_TILE_N);
    uint32_t gridZ = batchCount > 0 ? (uint32_t)batchCount : 1;

    vkCmdDispatch(cmd, gridX, gridY, gridZ);

    return VK_SUCCESS;
}

VkResult vkblas_sgemm(VkBLASContext*  context,
                      VkCommandBuffer cmd,
                      VkBLASOperation_t transA,
                      VkBLASOperation_t transB,
                      int32_t           m,
                      int32_t           n,
                      int32_t           k,
                      const float*      alpha,
                      VkBuffer          A,
                      int32_t           lda,
                      VkBuffer          B,
                      int32_t           ldb,
                      const float*      beta,
                      VkBuffer          C,
                      int32_t           ldc,
                      VkBuffer          D,
                      int32_t           ldd)
{
    if (!context || !cmd || !A || !B || !D || !alpha || !beta)
        return VK_ERROR_INITIALIZATION_FAILED;
    if (m <= 0 || n <= 0 || k <= 0)
        return VK_SUCCESS;  /* no-op for zero-dim matrices */

    return vkblas_sgemm_common(context, cmd, transA, transB,
                               m, n, k, alpha, A, lda, B, ldb,
                               beta, C, ldc, D, ldd,
                               0, 0, 0, 0, 1, VK_FALSE);
}

VkResult vkblas_sgemm_strided_batched(VkBLASContext*    context,
                                      VkCommandBuffer   cmd,
                                      VkBLASOperation_t transA,
                                      VkBLASOperation_t transB,
                                      int32_t           m,
                                      int32_t           n,
                                      int32_t           k,
                                      const float*      alpha,
                                      VkBuffer          A,
                                      int32_t           lda,
                                      int64_t           strideA,
                                      VkBuffer          B,
                                      int32_t           ldb,
                                      int64_t           strideB,
                                      const float*      beta,
                                      VkBuffer          C,
                                      int32_t           ldc,
                                      int64_t           strideC,
                                      VkBuffer          D,
                                      int32_t           ldd,
                                      int64_t           strideD,
                                      int32_t           batchCount)
{
    if (!context || !cmd || !A || !B || !D || !alpha || !beta)
        return VK_ERROR_INITIALIZATION_FAILED;
    if (m <= 0 || n <= 0 || k <= 0 || batchCount <= 0)
        return VK_SUCCESS;

    /* Strides are in bytes in the API but elements in the shader */
    uint32_t elem_strideA = (uint32_t)(strideA / sizeof(float));
    uint32_t elem_strideB = (uint32_t)(strideB / sizeof(float));
    uint32_t elem_strideC = (uint32_t)(strideC / sizeof(float));
    uint32_t elem_strideD = (uint32_t)(strideD / sizeof(float));

    return vkblas_sgemm_common(context, cmd, transA, transB,
                               m, n, k, alpha, A, lda, B, ldb,
                               beta, C, ldc, D, ldd,
                               elem_strideA, elem_strideB,
                               elem_strideC, elem_strideD,
                               batchCount, VK_TRUE);
}

VkResult vkblas_sgemm_batched(VkBLASContext*    context,
                              VkCommandBuffer   cmd,
                              VkBLASOperation_t transA,
                              VkBLASOperation_t transB,
                              int32_t           m,
                              int32_t           n,
                              int32_t           k,
                              const float*      alpha,
                              const VkBLASBufferLoc* A,
                              int32_t           lda,
                              const VkBLASBufferLoc* B,
                              int32_t           ldb,
                              const float*      beta,
                              const VkBLASBufferLoc* C,
                              int32_t           ldc,
                              VkBLASBufferLoc*  D,
                              int32_t           ldd,
                              int32_t           batchCount)
{
    /* Batched GEMM with per-matrix buffer arrays: implement as a loop
       of single GEMMs, each with its own buffer bindings. This is not
       optimal but correct — the caller can use strided_batched for
       better performance when matrices are contiguous. */
    if (!context || !cmd || !A || !B || !D || !alpha || !beta)
        return VK_ERROR_INITIALIZATION_FAILED;
    if (m <= 0 || n <= 0 || k <= 0 || batchCount <= 0)
        return VK_SUCCESS;

    for (int32_t b = 0; b < batchCount; ++b) {
        VkBuffer bufA = (A[b].buffer != VK_NULL_HANDLE) ? A[b].buffer : A->buffer;
        VkBuffer bufB = (B[b].buffer != VK_NULL_HANDLE) ? B[b].buffer : B->buffer;
        VkBuffer bufC = (C && C[b].buffer != VK_NULL_HANDLE) ? C[b].buffer : A->buffer;
        VkBuffer bufD = (D[b].buffer != VK_NULL_HANDLE) ? D[b].buffer : A->buffer;

        VkResult r = vkblas_sgemm_common(context, cmd, transA, transB,
                                         m, n, k, alpha,
                                         bufA, lda, bufB, ldb,
                                         beta, bufC, ldc, bufD, ldd,
                                         0, 0, 0, 0, 1, VK_FALSE);
        if (r != VK_SUCCESS) return r;
    }
    return VK_SUCCESS;
}

