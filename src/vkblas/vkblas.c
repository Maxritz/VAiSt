/* ── Pipeline cache lookup / creation ─────────────────────────────────────── */

static uint32_t vkblas_hash_to_slot(uint64_t key)
{
    /* Simple multiplicative hash + modulo (power-of-two table) */
    key ^= key >> 32;
    key *= 0x9e3779b97f4a7c15ULL;
    return (uint32_t)(key & (VKBLAS_MAX_PIPELINES - 1));
}

static VkPipeline vkblas_get_cached_pipeline_tier(VkBLASContext* ctx,
                                                  uint32_t data_type,
                                                  VkBool32 transA,
                                                  VkBool32 transB,
                                                  VkBool32 is_strided,
                                                  VkBLASTier_t tier)
{
    uint64_t key = vkblas_hash_key(data_type, transA, transB, is_strided,
                                   (uint32_t)tier);
    uint32_t slot = vkblas_hash_to_slot(key);

    for (uint32_t i = 0; i < VKBLAS_MAX_PIPELINES; ++i) {
        uint32_t idx = (slot + i) & (VKBLAS_MAX_PIPELINES - 1);
        if (!ctx->pipelines[idx].valid)
            break;
        if (ctx->pipelines[idx].key == key)
            return ctx->pipelines[idx].pipeline;
    }
    return VK_NULL_HANDLE;
}

VkPipeline vkblas_get_cached_pipeline(VkBLASContext* ctx,
                                       uint32_t data_type,
                                       VkBool32 transA, VkBool32 transB,
                                       VkBool32 is_strided)
{
    /* Search from the active tier down so a cached lower-tier fallback
       (e.g. f16 baseline) is found even when a higher tier is active. */
    int t = (int)ctx->active_tier;
    while (t >= (int)VKBLAS_TIER_BASELINE) {
        VkPipeline p = vkblas_get_cached_pipeline_tier(ctx, data_type, transA,
                                                       transB, is_strided,
                                                       (VkBLASTier_t)t);
        if (p != VK_NULL_HANDLE)
            return p;
        --t;
    }
    return VK_NULL_HANDLE;
}

VkResult vkblas_ensure_pipeline(VkBLASContext* ctx,
                                uint32_t data_type,
                                uint32_t transA, uint32_t transB,
                                uint32_t is_strided,
                                VkPipeline* out_pipeline)
{
    /* Try cache first (searches all tiers) */
    VkPipeline cached = vkblas_get_cached_pipeline(ctx, data_type,
                                                   transA, transB, is_strided);
    if (cached != VK_NULL_HANDLE) {
        *out_pipeline = cached;
        return VK_SUCCESS;
    }

    /* Attempt to create a pipeline, trying the active tier first and
       falling back to lower tiers (per AGENTS.md fallback chain). */
    VkResult last_result = VK_ERROR_FEATURE_NOT_PRESENT;

    int t = (int)ctx->active_tier;
    while (t >= (int)VKBLAS_TIER_BASELINE) {
        VkBLASTier_t tier = (VkBLASTier_t)t;

        /* Select SPIR-V blob for this tier */
        size_t spirv_size = 0;
        const uint32_t* spirv = vkblas_select_spirv(ctx, data_type, tier,
                                                    &spirv_size);
        if (spirv == NULL) {
            --t;
            continue;
        }

        /* Create shader module */
        VkShaderModule sm;
        VkResult r = vkblas_load_shader_module(ctx->device, spirv,
                                               spirv_size, &sm);
        if (r != VK_SUCCESS) {
            last_result = r;
            --t;
            continue;
        }

        /* Specialization constants */
        uint32_t sc_data[7];
        vkblas_fill_sc_data(sc_data, tier);

        VkSpecializationInfo si = {
            .mapEntryCount = 7,
            .pMapEntries   = vkblas_sc_map,
            .dataSize      = sizeof(sc_data),
            .pData         = sc_data,
        };

        VkPipelineLayout pl = (data_type >= VKBLAS_DTYPE_CONV_RB2_F32 &&
                               data_type <= VKBLAS_DTYPE_CONV_RB2_F64)
                                  ? ctx->conv_pipeline_layout : ctx->pipeline_layout;

        VkComputePipelineCreateInfo cpci = {
            .sType  = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO,
            .stage  = {
                .sType  = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
                .stage  = VK_SHADER_STAGE_COMPUTE_BIT,
                .module = sm,
                .pName  = "main",
                .pSpecializationInfo = &si,
            },
            .layout = pl,
        };

        VkPipeline pipeline;
        r = vkCreateComputePipelines(ctx->device, ctx->pipeline_cache, 1, &cpci,
                                      NULL, &pipeline);
        vkDestroyShaderModule(ctx->device, sm, NULL);
        if (r != VK_SUCCESS) {
            last_result = r;
            --t;
            continue;
        }

        /* Insert into cache under the tier actually used */
        uint64_t key = vkblas_hash_key(data_type, transA, transB, is_strided,
                                       (uint32_t)tier);
        uint32_t slot = vkblas_hash_to_slot(key);

        for (uint32_t i = 0; i < VKBLAS_MAX_PIPELINES; ++i) {
            uint32_t idx = (slot + i) & (VKBLAS_MAX_PIPELINES - 1);
            if (!ctx->pipelines[idx].valid) {
                ctx->pipelines[idx].key        = key;
                ctx->pipelines[idx].pipeline   = pipeline;
                ctx->pipelines[idx].layout     =
                    (data_type >= VKBLAS_DTYPE_CONV_RB2_F32 &&
                     data_type <= VKBLAS_DTYPE_CONV_RB2_F64)
                        ? ctx->conv_pipeline_layout : ctx->pipeline_layout;
                ctx->pipelines[idx].data_type  = data_type;
                ctx->pipelines[idx].transA     = transA;
                ctx->pipelines[idx].transB     = transB;
                ctx->pipelines[idx].is_strided = is_strided;
                ctx->pipelines[idx].tier       = (uint32_t)tier;
                ctx->pipelines[idx].valid      = 1;
                ctx->pipeline_count++;
                break;
            }
        }

        *out_pipeline = pipeline;
        return VK_SUCCESS;
    }

    return last_result;
}

/* ── Descriptor set allocation ────────────────────────────────────────────── */

VkResult vkblas_alloc_descriptor_set(VkBLASContext* ctx, VkDescriptorSet* out)
{
    VkDescriptorSetAllocateInfo dsai = {
        .sType              = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO,
        .descriptorPool     = ctx->descriptor_pool,
        .descriptorSetCount = 1,
        .pSetLayouts        = &ctx->set_layout,
    };
    return vkAllocateDescriptorSets(ctx->device, &dsai, out);
}

/* ── Descriptor set write ─────────────────────────────────────────────────── */

void vkblas_write_descriptor_set(VkBLASContext* ctx, VkDescriptorSet ds,
                                 VkBuffer A, VkBuffer B, VkBuffer C, VkBuffer D)
{
    VkDescriptorBufferInfo bi[4] = {
        { A, 0, VK_WHOLE_SIZE },
        { B, 0, VK_WHOLE_SIZE },
        { C, 0, VK_WHOLE_SIZE },
        { D, 0, VK_WHOLE_SIZE },
    };

    VkWriteDescriptorSet writes[4] = {
        { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = ds, .dstBinding = 0,
          .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
          .pBufferInfo = &bi[0] },
        { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = ds, .dstBinding = 1,
          .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
          .pBufferInfo = &bi[1] },
        { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = ds, .dstBinding = 2,
          .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
          .pBufferInfo = &bi[2] },
        { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = ds, .dstBinding = 3,
          .descriptorCount = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
          .pBufferInfo = &bi[3] },
    };

    vkUpdateDescriptorSets(ctx->device, 4, writes, 0, NULL);
}

/* ── Convolution dispatch ────────────────────────────────────────────────── */

/* Records a single rb2 conv dispatch. The conv shaders read bindings
 * 0 = x, 1 = w, 2 = y and use the conv-specific push-constant block; the
 * shared 4-binding set layout is compatible (binding 3 is simply unused).
 * Grid: one workgroup per k and n, gx covers spatial pairs in 512-thread
 * workgroups (RB=2 outputs per thread). */
VkResult vkblas_conv_common(VkBLASContext* ctx,
                            VkCommandBuffer cmd,
                            uint32_t dtype,
                            uint32_t n, uint32_t c,
                            uint32_t di, uint32_t hi, uint32_t wi,
                            uint32_t k, uint32_t dd, uint32_t dh, uint32_t dw,
                            uint32_t kd, uint32_t kh, uint32_t kw,
                            uint32_t pad_d, uint32_t pad_h, uint32_t pad_w,
                            uint32_t stride_d, uint32_t stride_h, uint32_t stride_w,
                            uint32_t dil_d, uint32_t dil_h, uint32_t dil_w,
                            float alpha, VkBuffer x, VkBuffer w,
                            float beta, VkBuffer y)
{
    if (!ctx || !cmd) return VK_ERROR_INITIALIZATION_FAILED;
    (void)beta; /* beta accumulation not yet fused into the rb2 kernel */

    VkPipeline pipeline;
    VkResult r = vkblas_ensure_pipeline(ctx, dtype, 0, 0, VK_FALSE, &pipeline);
    if (r != VK_SUCCESS) return r;

    VkDescriptorSet ds;
    r = vkblas_alloc_descriptor_set(ctx, &ds);
    if (r != VK_SUCCESS) return r;
    /* binding 3 reused as y (unused by the shader) */
    vkblas_write_descriptor_set(ctx, ds, x, w, y, y);

    vkblas_conv_push_constants_t pc;
    memset(&pc, 0, sizeof(pc));
    pc.n = n; pc.c = c; pc.di = di; pc.hi = hi; pc.wi = wi;
    pc.k = k; pc.dd = dd; pc.dh = dh; pc.dw = dw;
    pc.kd = kd; pc.kh = kh; pc.kw = kw;
    pc.pad_d = pad_d; pc.pad_h = pad_h; pc.pad_w = pad_w;
    pc.stride_d = stride_d; pc.stride_h = stride_h; pc.stride_w = stride_w;
    pc.dil_d = dil_d; pc.dil_h = dil_h; pc.dil_w = dil_w;
    pc.alpha = alpha; pc.beta = beta;

    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE,
                            ctx->conv_pipeline_layout, 0, 1, &ds, 0, NULL);
    vkCmdPushConstants(cmd, ctx->conv_pipeline_layout, VK_SHADER_STAGE_COMPUTE_BIT,
                       0, sizeof(pc), &pc);

    uint32_t spatial = dd * dh * dw;
    uint32_t pairs   = (spatial + 1u) / 2u;
    uint32_t gx      = (pairs + 511u) / 512u;
    vkCmdDispatch(cmd, gx, k, n);
    return VK_SUCCESS;
}

/* ── Push constants ───────────────────────────────────────────────────────── */

void vkblas_push_pc(VkCommandBuffer cmd, VkPipelineLayout layout,
                    const vkblas_push_constants_t* pc)
{
    vkCmdPushConstants(cmd, layout, VK_SHADER_STAGE_COMPUTE_BIT,
                       0, sizeof(vkblas_push_constants_t), pc);
}

/* ── Context lifecycle ────────────────────────────────────────────────────── */

VkResult vkblas_create_context(VkInstance instance,
                               VkPhysicalDevice physicalDevice,
                               VkDevice device,
                               VkBLASContext** pContext)
{
    if (!pContext) return VK_ERROR_INITIALIZATION_FAILED;

    VkBLASContext* ctx = (VkBLASContext*)malloc(sizeof(VkBLASContext));
    if (!ctx) return VK_ERROR_OUT_OF_HOST_MEMORY;

    memset(ctx, 0, sizeof(*ctx));
    ctx->instance = instance;
    ctx->device = device;

    /* Pipeline cache via VKRuntime helper */
    VkResult r = vkr_create_pipeline_cache(device, &ctx->pipeline_cache);
    if (r != VK_SUCCESS) goto fail;

    /* Descriptor pool via VKRuntime helper */
    r = vkr_create_descriptor_pool(device, VKBLAS_MAX_PIPELINES,
                                   VKBLAS_MAX_PIPELINES, &ctx->descriptor_pool);
    if (r != VK_SUCCESS) goto fail;

    /* Descriptor set layout (lib-specific, stays local) */
    r = vkblas_create_set_layout(ctx);
    if (r != VK_SUCCESS) goto fail;

    /* Pipeline layout via VKRuntime helper; the push-constant range is
       lib-specific and stays local. */
    VkPushConstantRange pcr = {
        .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
        .offset     = 0,
        .size       = sizeof(vkblas_push_constants_t),
    };
    r = vkr_create_pipeline_layout(device, ctx->set_layout, 1, &pcr,
                                   &ctx->pipeline_layout);
    if (r != VK_SUCCESS) goto fail;

    /* Conv pipeline layout: the conv push-constant block (92 B) exceeds the
       GEMM block (84 B), so it needs its own layout with a wider range. */
    VkPushConstantRange conv_pcr = {
        .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
        .offset     = 0,
        .size       = sizeof(vkblas_conv_push_constants_t),
    };
    r = vkr_create_pipeline_layout(device, ctx->set_layout, 1, &conv_pcr,
                                   &ctx->conv_pipeline_layout);
    if (r != VK_SUCCESS) goto fail;

    /* Detect capabilities via VKRuntime (single implementation). */
    VkRuntimeCaps caps;
    r = vkr_detect_capabilities(physicalDevice, device, &caps);
    if (r != VK_SUCCESS) {
        /* Fall back to baseline if detection fails */
        ctx->active_tier = VKBLAS_TIER_BASELINE;
        ctx->has_subgroup = VK_FALSE;
        ctx->has_coop_matrix = VK_FALSE;
    } else {
        ctx->has_subgroup = caps.has_subgroup;
        ctx->has_coop_matrix = caps.has_coop_matrix;
        ctx->max_subgroup_size = caps.subgroup_size;
        ctx->max_compute_workgroup_size[0] = caps.max_workgroup_size[0];
        ctx->max_compute_workgroup_size[1] = caps.max_workgroup_size[1];
        ctx->max_compute_workgroup_size[2] = caps.max_workgroup_size[2];

        /* Driver-guarded cooperative-matrix path (see AGENTS.md): default OFF
           because the AMD 26.7.1 Windows driver hard-crashes
           (0xE06D7363) inside vkCreateComputePipelines for modules containing
           coopMatMulAddKHR. Enabled only when VAIT_COOPMATRIX is set. */
        ctx->use_coopmat = (getenv("VAIT_COOPMATRIX") != NULL) &&
                            (ctx->has_coop_matrix == VK_TRUE);

        /* Ground-truth: enumerate the cooperative-matrix shapes this device
           actually advertises, so the f16/bf16/f64 coopmatrix tiers are
           matched to reported (MSize,NSize,KSize,AType,BType,CType,ResultType).
           Printed only while diagnosing under VAIT_COOPMATRIX. */
        /* Ground-truth: enumerate the cooperative-matrix shapes this device
           actually advertises, so the f16/bf16/f64 coopmatrix tiers are
           matched to reported (MSize,NSize,KSize,AType,BType,CType,ResultType).
           Printed only while diagnosing under VAIT_COOPMATRIX. */
        if (ctx->use_coopmat) {
            PFN_vkGetPhysicalDeviceCooperativeMatrixPropertiesKHR gpm =
                (PFN_vkGetPhysicalDeviceCooperativeMatrixPropertiesKHR)
                vkGetInstanceProcAddr(instance,
                     "vkGetPhysicalDeviceCooperativeMatrixPropertiesKHR");
            uint32_t n = 0;
            if (gpm && gpm(physicalDevice, &n, NULL) == VK_SUCCESS && n > 0) {
                VkCooperativeMatrixPropertiesKHR *cmprops =
                    (VkCooperativeMatrixPropertiesKHR *)calloc(n, sizeof(*cmprops));
                if (cmprops) {
                    for (uint32_t i = 0; i < n; i++)
                        cmprops[i].sType =
                            VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_COOPERATIVE_MATRIX_PROPERTIES_KHR;
                    if (gpm(physicalDevice, &n, cmprops) == VK_SUCCESS) {
                        for (uint32_t i = 0; i < n; i++)
                            printf("vkblas: coopmatrix[%u] %ux%ux%u A=%u B=%u C=%u R=%u scope=%u\n",
                                   i, cmprops[i].MSize, cmprops[i].NSize, cmprops[i].KSize,
                                   (unsigned)cmprops[i].AType, (unsigned)cmprops[i].BType,
                                   (unsigned)cmprops[i].CType, (unsigned)cmprops[i].ResultType,
                                   (unsigned)cmprops[i].scope);
                    }
                    free(cmprops);
                }
            }
        }

        if (ctx->use_coopmat && ctx->has_subgroup) {
            ctx->active_tier = VKBLAS_TIER_COOPMATRIX;
        } else if (ctx->has_subgroup) {
            ctx->active_tier = VKBLAS_TIER_SUBGROUP;
        } else {
            ctx->active_tier = VKBLAS_TIER_BASELINE;
        }
    }

    *pContext = ctx;
    return VK_SUCCESS;

fail:
    if (ctx->pipeline_cache)
        vkDestroyPipelineCache(device, ctx->pipeline_cache, NULL);
    if (ctx->descriptor_pool)
        vkDestroyDescriptorPool(device, ctx->descriptor_pool, NULL);
    if (ctx->set_layout)
        vkDestroyDescriptorSetLayout(device, ctx->set_layout, NULL);
    if (ctx->pipeline_layout)
        vkDestroyPipelineLayout(device, ctx->pipeline_layout, NULL);
    free(ctx);
    return r;
}

void vkblas_destroy_context(VkBLASContext* context)
{
    if (!context) return;

    for (uint32_t i = 0; i < VKBLAS_MAX_PIPELINES; ++i) {
        if (context->pipelines[i].valid)
            vkDestroyPipeline(context->device, context->pipelines[i].pipeline, NULL);
    }

    if (context->pipeline_cache)
        vkDestroyPipelineCache(context->device, context->pipeline_cache, NULL);
    if (context->descriptor_pool)
        vkDestroyDescriptorPool(context->device, context->descriptor_pool, NULL);
    if (context->set_layout)
        vkDestroyDescriptorSetLayout(context->device, context->set_layout, NULL);
    if (context->pipeline_layout)
        vkDestroyPipelineLayout(context->device, context->pipeline_layout, NULL);
    if (context->conv_pipeline_layout)
        vkDestroyPipelineLayout(context->device, context->conv_pipeline_layout, NULL);

    free(context);
}

uint32_t vkblas_get_arch_index(VkBLASContext* context)
{
    return (uint32_t)context->active_tier;
}

const char* vkblas_get_arch_name(VkBLASContext* context)
{
    switch (context->active_tier) {
    case VKBLAS_TIER_BASELINE:   return "baseline";
    case VKBLAS_TIER_SUBGROUP:   return "subgroup";
    case VKBLAS_TIER_COOPMATRIX: return "coopmatrix";
    default:                     return "unknown";
    }
}

/* ── Capability detection ─────────────────────────────────────────────────── */

VkResult vkblas_init_capabilities(VkBLASContext* ctx, VkPhysicalDevice pd)
{
    if (!ctx) return VK_ERROR_INITIALIZATION_FAILED;

    /* Single VKRuntime implementation: subgroup / cooperative-matrix /
       shaderInt64 detection plus push-desc fn load. */
    VkRuntimeCaps caps;
    VkResult r = vkr_detect_capabilities(pd, ctx->device, &caps);
    if (r != VK_SUCCESS) return r;

    ctx->has_subgroup = caps.has_subgroup;
    ctx->has_coop_matrix = caps.has_coop_matrix;
    ctx->max_subgroup_size = caps.subgroup_size;
    ctx->max_compute_workgroup_size[0] = caps.max_workgroup_size[0];
    ctx->max_compute_workgroup_size[1] = caps.max_workgroup_size[1];
    ctx->max_compute_workgroup_size[2] = caps.max_workgroup_size[2];

    /* Select highest tier.
       The cooperative-matrix tier is SELECTABLE but dormant by default: the
       AMD 26.7.1 Windows driver crashes the whole process (0xE06D7363) inside
       vkCreateComputePipelines when compiling a module that contains
       coopMatMulAddKHR. We therefore only route through the coopmatrix shader
       when the operator explicitly opts in via VAIT_COOPMATRIX. */
    ctx->use_coopmat = (getenv("VAIT_COOPMATRIX") != NULL) &&
                       (ctx->has_coop_matrix == VK_TRUE);
    if (ctx->use_coopmat && ctx->has_subgroup) {
        ctx->active_tier = VKBLAS_TIER_COOPMATRIX;
    } else if (ctx->has_subgroup) {
        ctx->active_tier = VKBLAS_TIER_SUBGROUP;
    } else {
        ctx->active_tier = VKBLAS_TIER_BASELINE;
    }

    return VK_SUCCESS;
}

void vkblas_flush_pipelines(VkBLASContext* ctx)
{
    for (uint32_t i = 0; i < VKBLAS_MAX_PIPELINES; ++i) {
        if (ctx->pipelines[i].valid) {
            vkDestroyPipeline(ctx->device, ctx->pipelines[i].pipeline, NULL);
            ctx->pipelines[i].valid = 0;
        }
    }
    ctx->pipeline_count = 0;
}

