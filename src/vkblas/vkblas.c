/* ── GEMM dispatch (generic over dtype) ──────────────────────────────────── */

/* Fill alpha/beta push-constant scalars for the data type.
   - f32: stored directly in pc.alpha/pc.beta.
   - f16: converted to f32 (exact) and stored in pc.alpha/pc.beta.
   - f64: raw double bits packed into the 8-byte slots at offsets 12..19
     (pc.alpha/pc.beta) and 76..83 (pc._pad2/pc._pad3); the f64 shader
     recombines them with packDouble2x32. */
static void vkblas_fill_scalars(uint32_t dtype, vkblas_push_constants_t* pc,
                                const void* alpha, const void* beta)
{
    pc->beta_is_zero = 0;

    switch (dtype) {
    case VKBLAS_DTYPE_F64: {
        double av = (alpha != NULL) ? *(const double*)alpha : 1.0;
        double bv = (beta  != NULL) ? *(const double*)beta  : 0.0;
        memcpy(&pc->alpha, &av, sizeof(av));   /* offsets 12..19 */
        memcpy(&pc->_pad2, &bv, sizeof(bv));   /* offsets 76..83 */
        if (bv == 0.0)
            pc->beta_is_zero = 1;
        break;
    }
    case VKBLAS_DTYPE_BF16: {
        /* bf16 alpha/beta: uint16 bits; promote to f32 via bits<<16. */
        float av = (alpha != NULL)
            ? vkblas_bf16_to_f32(*(const uint16_t*)alpha) : 1.0f;
        float bv = (beta != NULL)
            ? vkblas_bf16_to_f32(*(const uint16_t*)beta) : 0.0f;
        pc->alpha = av;
        pc->beta  = bv;
        if (bv == 0.0f)
            pc->beta_is_zero = 1;
        break;
    }
    case VKBLAS_DTYPE_F16: {
        float av = (alpha != NULL)
            ? vkblas_f16_to_f32(*(const uint16_t*)alpha) : 1.0f;
        float bv = (beta != NULL)
            ? vkblas_f16_to_f32(*(const uint16_t*)beta) : 0.0f;
        pc->alpha = av;
        pc->beta  = bv;
        if (bv == 0.0f)
            pc->beta_is_zero = 1;
        break;
    }
    default: /* f32 */
        pc->alpha = (alpha != NULL) ? *(const float*)alpha : 1.0f;
        pc->beta  = (beta  != NULL) ? *(const float*)beta  : 0.0f;
        if (pc->beta == 0.0f)
            pc->beta_is_zero = 1;
        break;
    }
}

/* Shared dispatch for every GEMM family member. alpha/beta are opaque
   pointers whose element type follows `dtype`. */
static VkResult vkblas_gemm_common(VkBLASContext*  ctx,
                                   VkCommandBuffer  cmd,
                                   VkBLASOperation_t transA,
                                   VkBLASOperation_t transB,
                                   int32_t          m,
                                   int32_t          n,
                                   int32_t          k,
                                   uint32_t         dtype,
                                   const void*      alpha,
                                   VkBuffer         A,
                                   int32_t          lda,
                                   VkBuffer         B,
                                   int32_t          ldb,
                                   const void*      beta,
                                   VkBuffer         C,
                                   int32_t          ldc,
                                   VkBuffer         D,
                                   int32_t          ldd,
                                   uint32_t         strideA,
                                   uint32_t         strideB,
                                   uint32_t         strideC,
                                   uint32_t         strideD,
                                   int32_t          batchCount,
                                   VkBool32         is_strided)
{
    /* Ensure pipeline exists */
    uint32_t tA = (transA == VKBLAS_OP_N) ? 0 : 1;
    uint32_t tB = (transB == VKBLAS_OP_N) ? 0 : 1;

    VkPipeline pipeline = VK_NULL_HANDLE;
    VkResult r = vkblas_ensure_pipeline(ctx, dtype, tA, tB, is_strided,
                                        &pipeline);
    if (r != VK_SUCCESS)
        return r;

    /* Allocate descriptor set */
    VkDescriptorSet ds;
    r = vkblas_alloc_descriptor_set(ctx, &ds);
    if (r != VK_SUCCESS)
        return r;

    vkblas_write_descriptor_set(ctx, ds, A, B,
                                (C != VK_NULL_HANDLE) ? C : A, D);
    /* Use A as dummy for C when beta==0 (read-only binding won't be accessed) */

    /* Bind pipeline and descriptor set */
    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, pipeline);
    vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE,
                            ctx->pipeline_layout, 0, 1, &ds, 0, NULL);

    /* Push constants */
    vkblas_push_constants_t pc = {0};
    pc.m = (uint32_t)m;
    pc.n = (uint32_t)n;
    pc.k = (uint32_t)k;
    vkblas_fill_scalars(dtype, &pc, alpha, beta);
    pc.lda = (uint32_t)lda;
    pc.ldb = (uint32_t)ldb;
    pc.ldc = (uint32_t)ldc;
    pc.ldd = (uint32_t)ldd;
    pc.transA = (int32_t)tA;
    pc.transB = (int32_t)tB;
    pc.strideA = strideA;
    pc.strideB = strideB;
    pc.strideC = strideC;
    pc.strideD = strideD;
    pc.batchCount = (uint32_t)batchCount;
    vkblas_push_pc(cmd, ctx->pipeline_layout, &pc);

    /* Compute grid: one workgroup per TILE_M × TILE_N output block */
    uint32_t gridX = (uint32_t)((m + VKBLAS_TILE_M - 1) / VKBLAS_TILE_M);
    uint32_t gridY = (uint32_t)((n + VKBLAS_TILE_N - 1) / VKBLAS_TILE_N);
    uint32_t gridZ = batchCount > 0 ? (uint32_t)batchCount : 1;

    vkCmdDispatch(cmd, gridX, gridY, gridZ);

    return VK_SUCCESS;
}

