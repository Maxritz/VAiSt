/* ── bf16 -> f32 conversion (CPU side) ──────────────────────────────────── */

/* bfloat16 is the high 16 bits of an IEEE-754 f32; zero the low mantissa
   bits and reinterpret. Handles 0/inf/nan exactly (all share the exponent). */
static float vkblas_bf16_to_f32(uint16_t b)
{
    uint32_t fbits = (uint32_t)b << 16;
    float f;
    memcpy(&f, &fbits, sizeof(f));
    return f;
}

/* ── f16 -> f32 conversion (CPU side) ───────────────────────────────────── */

static float vkblas_f16_to_f32(uint16_t h)
{
    uint32_t sign = (uint32_t)(h & 0x8000u) << 16;
    uint32_t exp  = (uint32_t)(h & 0x7C00u) >> 10;
    uint32_t man  = (uint32_t)(h & 0x03FFu);
    uint32_t fbits;

    if (exp == 0) {
        if (man == 0) {
            fbits = sign;                                   /* +/-0 */
        } else {
            /* subnormal: normalize into the normal exponent range */
            int e = 1;
            while ((man & 0x0400u) == 0u) { man <<= 1; --e; }
            man &= 0x03FFu;
            fbits = sign | ((uint32_t)(e + 112) << 23) | (man << 13);
        }
    } else if (exp == 0x1Fu) {
        fbits = sign | 0x7F800000u | (man << 13);           /* inf/nan */
    } else {
        fbits = sign | ((exp + 112u) << 23) | (man << 13);
    }

    float f;
    memcpy(&f, &fbits, sizeof(f));
    return f;
}

/* ── Specialization constant values ──────────────────────────────────────── */

#define VKBLAS_TILE_M 16
#define VKBLAS_TILE_N 16
#define VKBLAS_TILE_K 16

/* ── Specialization constant map (same for all f32 tiers) ────────────────── */

static VkSpecializationMapEntry vkblas_sc_map[] = {
    { 0, 0, sizeof(uint32_t) },   /* TILE_M */
    { 1, 4, sizeof(uint32_t) },   /* TILE_N */
    { 2, 8, sizeof(uint32_t) },   /* TILE_K */
    { 3, 12, sizeof(uint32_t) },  /* SG_WIDTH (subgroup) */
    { 4, 16, sizeof(uint32_t) },  /* CM_MSIZE (coopmatrix) */
    { 5, 20, sizeof(uint32_t) },  /* CM_NSIZE (coopmatrix) */
    { 6, 24, sizeof(uint32_t) },  /* CM_KSIZE (coopmatrix) */
};

/* ── Forward declarations for SPIR-V blobs ────────────────────────────────── */
/* Declared in shaders_spv.h — generated by compile_shaders.ps1 */

/* ── Hash function ───────────────────────────────────────────────────────── */

uint64_t vkblas_hash_key(uint32_t dt, uint32_t tA, uint32_t tB,
                         uint32_t strided, uint32_t tier)
{
    uint64_t h = (uint64_t)dt;
    h = h * 31 + tA;
    h = h * 31 + tB;
    h = h * 31 + strided;
    h = h * 31 + tier;
    h = h * 31 + VKBLAS_TILE_M;
    h = h * 31 + VKBLAS_TILE_N;
    h = h * 31 + VKBLAS_TILE_K;
    return h;
}

/* ── Shader blob selector ────────────────────────────────────────────────── */

/* Select the SPIR-V blob for an exact (data_type, tier) pair. Returns NULL
   when that combination has no shader (e.g. f16/f64 only exist at baseline);
   the caller falls back to lower tiers per the AGENTS.md fallback chain. */
static const uint32_t* vkblas_select_spirv(VkBLASContext* ctx,
                                           uint32_t data_type,
                                           VkBLASTier_t tier,
                                           size_t* out_size)
{
    (void)ctx;
    switch (tier) {
    case VKBLAS_TIER_COOPMATRIX:
        /* Real coop-matrix shader is dormant unless explicitly enabled via
           VAIT_COOPMATRIX; AMD 26.7.1 crashes on coopMatMulAddKHR pipelines.
           When disabled, fall through to the shared-memory tiers below. */
        if (ctx->use_coopmat != VK_TRUE)
            return NULL;
        switch (data_type) {
        case VKBLAS_DTYPE_F32:
            *out_size = vkblas_spv_coopmatrix_gemm_f32_size;
            return vkblas_spv_coopmatrix_gemm_f32;
        default:
            return NULL;
        }
    case VKBLAS_TIER_SUBGROUP:
        switch (data_type) {
        case VKBLAS_DTYPE_F32:
            *out_size = vkblas_spv_subgroup_gemm_f32_size;
            return vkblas_spv_subgroup_gemm_f32;
        default:
            return NULL;
        }
    case VKBLAS_TIER_BASELINE:
        switch (data_type) {
        case VKBLAS_DTYPE_F32:
            *out_size = vkblas_spv_baseline_gemm_f32_size;
            return vkblas_spv_baseline_gemm_f32;
        case VKBLAS_DTYPE_F16:
            *out_size = vkblas_spv_baseline_gemm_f16_size;
            return vkblas_spv_baseline_gemm_f16;
        case VKBLAS_DTYPE_BF16:
            *out_size = vkblas_spv_baseline_gemm_bf16_size;
            return vkblas_spv_baseline_gemm_bf16;
        case VKBLAS_DTYPE_F64:
            *out_size = vkblas_spv_baseline_gemm_f64_size;
            return vkblas_spv_baseline_gemm_f64;
        case VKBLAS_DTYPE_QGEMM_Q8_0:
            *out_size = vkblas_spv_baseline_qgemm_q8_0_size;
            return vkblas_spv_baseline_qgemm_q8_0;
        case VKBLAS_DTYPE_QGEMM_Q4K:
            *out_size = vkblas_spv_baseline_qgemm_q4k_size;
            return vkblas_spv_baseline_qgemm_q4k;
        case VKBLAS_DTYPE_QGEMM_Q4_0:
            *out_size = vkblas_spv_baseline_qgemm_q4_0_size;
            return vkblas_spv_baseline_qgemm_q4_0;
        case VKBLAS_DTYPE_QGEMM_Q5K:
            *out_size = vkblas_spv_baseline_qgemm_q5k_size;
            return vkblas_spv_baseline_qgemm_q5k;
        case VKBLAS_DTYPE_QGEMM_Q6K:
            *out_size = vkblas_spv_baseline_qgemm_q6k_size;
            return vkblas_spv_baseline_qgemm_q6k;
        case VKBLAS_DTYPE_QGEMM_Q3K:
            *out_size = vkblas_spv_baseline_qgemm_q3k_size;
            return vkblas_spv_baseline_qgemm_q3k;
        case VKBLAS_DTYPE_QGEMM_IQ4XS:
            *out_size = vkblas_spv_baseline_qgemm_iq4xs_size;
            return vkblas_spv_baseline_qgemm_iq4xs;
        default:
            return NULL;
        }
    default:
        return NULL;
    }
}

/* ── Specialization constant data ─────────────────────────────────────────── */

static void vkblas_fill_sc_data(uint32_t* data, VkBLASTier_t tier)
{
    (void)tier;
    data[0] = VKBLAS_TILE_M;   /* constant_id 0 */
    data[1] = VKBLAS_TILE_N;   /* constant_id 1 */
    data[2] = VKBLAS_TILE_K;   /* constant_id 2 */
    data[3] = 32;              /* SG_WIDTH (constant_id 3) */
    data[4] = 16;              /* CM_MSIZE (constant_id 4) */
    data[5] = 16;              /* CM_NSIZE (constant_id 5) */
    data[6] = 16;              /* CM_KSIZE (constant_id 6) */
}

