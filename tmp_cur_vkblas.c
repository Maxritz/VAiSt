VkResult vkblas_sgemm_batched(VkBLASContext*    context,
                              VkCommandBuffer   cmd,
                              VkBLASOperation_t transA,
                              VkBLASOperation_t transB,
                              int32_t           m,
                              int32_t           n,
                              int32_t           k,
                              const float*      alpha,
                              const VkBLASBufferLoc* A,
                              int32_t           lda,
                              const VkBLASBufferLoc* B,
                              int32_t           ldb,
                              const float*      beta,
                              const VkBLASBufferLoc* C,
                              int32_t           ldc,
                              VkBLASBufferLoc*  D,
                              int32_t           ldd,
                              int32_t           batchCount)
{
    /* Batched GEMM with per-matrix buffer arrays: implement as a loop
       of single GEMMs, each with its own buffer bindings. This is not
       optimal but correct — the caller can use strided_batched for
       better performance when matrices are contiguous. */
    if (!context || !cmd || !A || !B || !D || !alpha || !beta)
        return VK_ERROR_INITIALIZATION_FAILED;
    if (m <= 0 || n <= 0 || k <= 0 || batchCount <= 0)
        return VK_SUCCESS;

    for (int32_t b = 0; b < batchCount; ++b) {
        VkBuffer bufA = (A[b].buffer != VK_NULL_HANDLE) ? A[b].buffer : A->buffer;
        VkBuffer bufB = (B[b].buffer != VK_NULL_HANDLE) ? B[b].buffer : B->buffer;
        VkBuffer bufC = (C && C[b].buffer != VK_NULL_HANDLE) ? C[b].buffer : A->buffer;
        VkBuffer bufD = (D[b].buffer != VK_NULL_HANDLE) ? D[b].buffer : A->buffer;

        VkResult r = vkblas_gemm_common(context, cmd, transA, transB,
                                        m, n, k, VKBLAS_DTYPE_F32,
                                        (const void*)alpha,
                                        bufA, lda, bufB, ldb,
                                        (const void*)beta, bufC, ldc, bufD, ldd,
                                        0, 0, 0, 0, 1, VK_FALSE);
        if (r != VK_SUCCESS) return r;
    }
    return VK_SUCCESS;
}

